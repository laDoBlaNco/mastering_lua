Introduction to Queues

A queue is a linear data structure that follows the "First In First Out"
(FIFO) primciple. It represents a collection of elements in which items
are added at the rear (enqueue) and removed from the front (dequeue)

Some common examples of queues in computer science include print spoilers
task scheduling, process management, network data packets, etc.

 Key Operations:
 - Enqueue: Adds an element to the rear of the queue
 - Dequeue: Removes and returns the element from the front of the queue
 - Front (Peek): Returns the element at the front of the queue without removing it
 - IsEmpty: Checks if the queue is empty
 - Size: Returns the number of elements in the queue
 
