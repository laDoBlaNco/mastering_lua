--[[
Introduction to Stacks

- A Stack is a linear data structure that only allows inserting, deleting and
  querying elements at one of its ends, which we call the top
- LIFO type structure (Last In, First Out), in which the last element that
  enters is the first element that leaves
- In C++ we declare a stack using stack<T> where T is a defined type
- Insert on the top is called 'push'
- removing from the top is called 'pop'
]]
